// Движение. Зеркало `ds/motion.md`.
//
// Перенесена та часть, которая живёт прямо в компонентах ДС: нажатие, фокус,
// раскрытие спойлера. Сцена постановки штампа сюда не входит — это не переход
// между состояниями, а собственная анимация с шестью шагами, и собирать её по
// месту нельзя (`motion.md`, «Постановка штампа»).
//
// Главный принцип оттуда же: **интерфейс статичен и почти бесцветен, цвет
// живёт в движении.** Любая анимация, добавляющая цвет, заканчивается
// возвратом к спокойному состоянию.

import 'package:flutter/animation.dart';

/// Кривые и длительности.
abstract final class Motion {
  // --- Кривые --------------------------------------------------------------

  /// Появление и исчезновение.
  static const easeOut = Cubic(0.23, 1, 0.32, 1);

  /// Перемещение по экрану.
  static const easeInOut = Cubic(0.77, 0, 0.175, 1);

  /// Шторка.
  static const easeDrawer = Cubic(0.32, 0.72, 0, 1);

  /// `ease-in` в системе нет намеренно: он начинается медленно ровно в тот
  /// момент, когда человек смотрит внимательнее всего.

  /// Появление мелкого элемента внутри строки: галочка в списке, крестик
  /// сброса. Перелетает цель примерно на 10 % и возвращается — тот же приём,
  /// что у пилюли навбара, только кривой, а не пружиной: здесь нечему
  /// набирать скорость, элемента до этого просто не было.
  static const easeOutBack = Cubic(0.34, 1.56, 0.64, 1);

  /// Раскрытие спойлера. Пологая: начинается медленнее, чем `ease-out`,
  /// и долго доводит хвост — раскрытие читается как «отодвинули», а не как
  /// «выстрелило».
  ///
  /// Числа не подобраны на глаз, а сняты с аккордеона motion-primitives,
  /// который назвала автор: там у высоты и прозрачности нет своего перехода,
  /// значит работает дефолт Motion 11 — `getDefaultTransition`, ветка
  /// не-трансформных значений: 300 мс, cubic-bezier(0.25, 0.1, 0.35, 1).
  /// В комментарии авторов библиотеки — «чуть более пологая версия
  /// браузерного ease».
  static const easeReveal = Cubic(0.25, 0.1, 0.35, 1);

  /// То же для поворота. Перелёт около 2.6 % — на четверти оборота это
  /// 2.4°, и это не придирка: доля считается от величины движения, а не
  /// от вида. Замерено покадрово (`test/motion_probe.dart`): при 1.56
  /// выходит 8.8° и шеврон болтается, при 1.18 — 0.9°, то есть пружинки
  /// нет вовсе. 1.30 — середина, в которой она есть и не мешает.
  ///
  /// Потребителя сейчас нет: делалась под шеврон спойлера, а шеврон убрали
  /// из макета. Кривая остаётся с замеренными числами — следующий поворот
  /// возьмёт готовое, а не начнёт подбор заново.
  static const easeOutSoftBack = Cubic(0.34, 1.30, 0.64, 1);

  // --- Длительности --------------------------------------------------------

  /// Нажатие: вход быстрый — система отвечает мгновенно.
  static const pressIn = Duration(milliseconds: 120);

  /// Возврат после отпускания медленнее входа: отпускание может быть спокойным.
  static const pressOut = Duration(milliseconds: 180);

  /// Заливка от точки нажатия. Заметно дольше просадки: пятну нужно время,
  /// чтобы прочитаться как расходящееся. На 120 мс — тех же, что у просадки, —
  /// круг успевает только мигнуть, и вместо пятна выходит резкая протирка.
  /// Мгновенность ответа держит просадка, она никуда не делась.
  static const washIn = Duration(milliseconds: 280);

  /// Радиус пятна растёт **равномерно**, а не по `ease-out`.
  ///
  /// Это не придирка к кривой, а причина, по которой первая сборка читалась
  /// вспышкой: `ease-out` в этой системе — почти экспонента (0.23, 1, 0.32, 1),
  /// она проходит четыре пятых пути за первую пятую времени. Замерено
  /// снимком на 110-й миллисекунде из 260: кнопка уже залита целиком.
  /// Равномерный рост показывает ровно то, что обещает, — расходящийся круг;
  /// остановки в конце не видно, потому что к тому моменту пятно уже за
  /// дальним углом.
  static const washGrowth = Curves.linear;

  /// Спойлер: высота, прозрачность и оборот значка. Было 200 мс, стало 300 —
  /// столько же, сколько у аккордеона motion-primitives. Это ровно потолок
  /// ([ceiling]) и предел: дальше раскрытие начнёт читаться как задержка.
  static const reveal = Duration(milliseconds: 300);

  /// Шторка: вход и выход.
  static const drawerIn = Duration(milliseconds: 350);
  static const drawerOut = Duration(milliseconds: 250);

  /// ToastError: вход и выход.
  static const toastIn = Duration(milliseconds: 250);
  static const toastOut = Duration(milliseconds: 200);

  /// Сколько плашка живёт на экране.
  ///
  /// Пол в отрасли — 4 с: столько держит `SnackBar` в самом Flutter
  /// (`_snackBarDisplayDuration`), столько же у Material в варианте «short».
  /// Берём 5: сообщение о сбое бывает в две строки, и четырёх секунд
  /// на него мало.
  static const toastLife = Duration(seconds: 5);

  /// То же, когда на плашке есть кнопка. Общее правило всех систем: с
  /// действием короткий таймер не ставят — человеку нужно заметить,
  /// прочитать и дотянуться. Десять секунд это Material «long».
  ///
  /// Плашка о состоянии (нет сети) не гаснет вовсе: состояние кончается
  /// не по таймеру. По таймеру исчезло бы сообщение, а сеть — нет.
  static const toastLifeAction = Duration(seconds: 10);

  /// Пилюля навбара летит не по кривой, а пружиной. Кривая с мягким доездом
  /// читается как вязкость: чем аккуратнее конец, тем сильнее ощущение, что
  /// система думает. Пружина доносит почти всё расстояние за первые сто с
  /// небольшим миллисекунд и на этом заканчивает.
  ///
  /// `ratio` ровно единица — критическое затухание: пилюля доезжает до цели
  /// и останавливается, не проскакивая. Было 0.72, то есть перелёт около 7 %
  /// с отскоком, плюс растяжение и сжатие об стенку. Снято 08.09.2026:
  /// «микроанимации должны быть минималистичны, а тут бесячи». Приём стоил
  /// внимания дороже, чем добавлял: таб переключают десятки раз за сеанс.
  static final tabSpring = SpringDescription.withDampingRatio(
    mass: 1,
    stiffness: 700,
    ratio: 1,
  );

  /// Наклон карточки под пальцем. Порт пружины по умолчанию из Motion 11
  /// (`springDefaults`: stiffness 100, damping 10, mass 1) — той самой,
  /// которую берёт `useSpring` без настроек, а значит и `Tilt`
  /// в motion-primitives. Затухание 0.5 — заметно пружинит; это не наш
  /// подбор, а число из образца.
  static final tiltSpring = SpringDescription(
    mass: 1,
    stiffness: 100,
    damping: 10,
  );

  /// Наибольший угол наклона, градусы. `rotationFactor` из Basic Tilt Card;
  /// у самого компонента по умолчанию 15, в примере — 8.
  ///
  /// Сторону наклона мы у образца не взяли: там карточка уходит от пальца,
  /// у нас — проседает под ним. См. `tiltSinkSpring`.
  static const tiltDegrees = 8.0;

  /// Просадка карточки в поверхность. Затухание критическое, и это
  /// противоположность `tiltSpring`: наклон пусть пружинит, а сама просадка
  /// — нет. Предмет, вдавленный в стол, обратно не подпрыгивает, и упругость
  /// на этой оси мгновенно возвращает ощущение, что карточка висит.
  static final tiltSinkSpring = SpringDescription.withDampingRatio(
    mass: 1,
    stiffness: 500,
    ratio: 1,
  );

  /// Появление по очереди. Порт `AnimatedGroup` из motion-primitives,
  /// пресет `scale`: прозрачность 0 → 1 и масштаб 0.8 → 1, шаг между
  /// соседями 100 мс (`staggerChildren: 0.1`).
  ///
  /// Своего перехода у пресета нет, значит работают дефолты Motion 11:
  /// прозрачность — тем же `ease-reveal` на 300 мс, что и раскрытие
  /// спойлера, а масштаб — пружиной `criticallyDampedSpring(1)`,
  /// то есть жёсткость 550 при затухании 30. Это ζ ≈ 0.64: перелёт около
  /// 7 %, еле заметный на восьмипроцентном пути.
  static const appearStagger = Duration(milliseconds: 100);
  static const appearFrom = 0.8;
  static final appearSpring = SpringDescription(
    mass: 1,
    stiffness: 550,
    damping: 30,
  );

  /// Потолок интерфейсной анимации. Штамп — сознательное исключение
  /// (600–700 мс), но он живёт не здесь.
  static const ceiling = Duration(milliseconds: 300);

  /// Просадка под пальцем. Не на отпускании — на нажатии.
  static const pressScale = 0.97;

  /// Для каталога и сверки.
  static const durations = <String, Duration>{
    'press-in': pressIn,
    'press-out': pressOut,
    'reveal': reveal,
    'wash-in': washIn,
    'drawer-in': drawerIn,
    'drawer-out': drawerOut,
    'toast-in': toastIn,
    'toast-out': toastOut,
    'toast-life': toastLife,
    'toast-life-action': toastLifeAction,
    // Переезда таба здесь нет намеренно: он идёт пружиной, а у пружины нет
    // длительности — она задаётся жёсткостью и затуханием (`tabSpring`).
    'ceiling': ceiling,
    'pop-in': popIn,
    'pop-out': popOut,
  };

  /// Появление и исчезновение мелочи. Короче раскрытия спойлера: элемент
  /// небольшой, и длинное появление читается как задержка.
  static const popIn = Duration(milliseconds: 180);
  static const popOut = Duration(milliseconds: 140);

  static const curves = <String, Cubic>{
    'ease-out': easeOut,
    'ease-in-out': easeInOut,
    'ease-drawer': easeDrawer,
    'ease-reveal': easeReveal,
    'ease-out-back': easeOutBack,
    'ease-out-soft-back': easeOutSoftBack,
  };
}
